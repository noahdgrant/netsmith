//! The pin map for the firmware author: `fab` writes `<board>.pins.h` and `<board>.pins.json`
//! into the board's `fab/` folder, from the pins the board was routed with, when it has pin
//! requests (ADR 0101), naming each signal by its request. `build` writes none: its pins are
//! provisional (owner decision of 2026-11-11).

use std::fs;
use std::path::Path;

use netsmith_fabricate::pin_export::{PinMap, render};
use netsmith_check::Loader;
use netsmith_testkit::TempDir;

const PART: &str = r#"
/// Zmcu4, an invented microcontroller: the datasheet names of its pins differ in how they end.
part Zmcu4 {
    peripheral UARTE0 on GPIO { UARTE0_TX:output UARTE0_RX:input }
    pins {
        .p00 bidirectional "GPIO7" "1" fn GPIO
        .p01 bidirectional "P0.13" "2" fn GPIO
        .p02 bidirectional "P0.02" "3" fn GPIO ANALOG
        .p03 bidirectional "P0.03" "4" fn GPIO ANALOG
    }
}
"#;

fn source(requests: &str) -> String {
    format!(
        "import std::parts::passive::Resistor\n{PART}\nboard Sensors {{\n    .u: Zmcu4\n    .load: Resistor\n{requests}\n}}\n"
    )
}

const REQUESTS: &str = "    .status: .u.GPIO\n    .sense: .u.ANALOG\n    .status ~ .load.a\n";

/// The pin map of the first board of `text`, with `pin_file` as the pin file beside it.
fn map_of(text: &str, pin_file: Option<&str>) -> Result<Option<PinMap>, String> {
    let dir = TempDir::new("pin-export");
    let path = dir.path().join("main.nsm");
    let mut loader = Loader::std();
    if let Some(file) = pin_file {
        fs::write(path.with_extension("pins.toml"), file).unwrap();
        netsmith_fabricate::pins::attach(&mut loader, "main.nsm", &path, &Default::default()).unwrap();
    }
    let outcome = netsmith_pipeline::outcome_with(
        "main.nsm",
        text,
        &loader,
        &netsmith_solve::Catalogs::jlcpcb(),
        None,
    )
    .map_err(|p| netsmith_pipeline::render_problems(&p))?;
    let b = &outcome.boards[0];
    let spaces = outcome
        .pins
        .spaces
        .get(&b.board)
        .map_or(&[][..], Vec::as_slice);
    render(&b.design, spaces, "main.nsm")
}

#[test]
fn the_header_names_each_signal_by_its_request() {
    let map = map_of(&source(REQUESTS), None).unwrap().unwrap();
    assert_eq!(
        map.header,
        r#"// Generated by netsmith from main.nsm. Do not edit: run `netsmith fab` again.
// The pins of the requests of board Sensors.
#ifndef SENSORS_PINS_H
#define SENSORS_PINS_H

// sense: pin P0.02, pad 3 of u, function ANALOG
#define SENSORS_PIN_SENSE_NAME "P0.02"
#define SENSORS_PIN_SENSE_FUNCTION "ANALOG"

// status: pin GPIO7, pad 1 of u, function GPIO
#define SENSORS_PIN_STATUS_NAME "GPIO7"
#define SENSORS_PIN_STATUS_FUNCTION "GPIO"
#define SENSORS_PIN_STATUS_NUMBER 7

#endif // SENSORS_PINS_H
"#
    );
}

#[test]
fn the_json_map_has_sorted_keys_and_the_lock_of_the_pin_file() {
    let file = "version = 1\n\n[Sensors.pins.sense]\npin = \"p02\"\nfunction = \"ANALOG\"\nlock = true\nsource = \"hand\"\n";
    let map = map_of(&source(REQUESTS), Some(file)).unwrap().unwrap();
    assert_eq!(
        map.json,
        r#"{
  "board": "Sensors",
  "signals": {
    "sense": {
      "function": "ANALOG",
      "locked": true,
      "pad": "3",
      "part": "u",
      "pin": "P0.02"
    },
    "status": {
      "function": "GPIO",
      "locked": false,
      "pad": "1",
      "part": "u",
      "pin": "GPIO7"
    }
  },
  "source": "main.nsm"
}
"#
    );
    assert!(
        map.header
            .contains("// sense: pin P0.02, pad 3 of u, function ANALOG, locked\n")
    );
}

#[test]
fn a_pin_name_without_one_trailing_number_has_no_numeric_macro() {
    // `.sense` gets `P0.02`: two numbers, so none is guessed.
    let map = map_of(&source(REQUESTS), None).unwrap().unwrap();
    assert!(!map.header.contains("SENSORS_PIN_SENSE_NUMBER"));
    assert!(map.header.contains("SENSORS_PIN_STATUS_NUMBER 7"));
}

#[test]
fn a_board_with_no_request_has_no_pin_map() {
    let text = "import std::parts::passive::Resistor\nboard Plain {\n    .a: Resistor\n    .b: Resistor\n    .a.a ~ .b.a\n}\n";
    assert_eq!(map_of(text, None).unwrap(), None);
}

#[test]
fn two_requests_that_are_one_signal_in_c_are_an_error_naming_both() {
    let text = source("    .a_b: .u.GPIO\n    .A_b: .u.GPIO\n    .a_b ~ .load.a\n");
    let e = map_of(&text, None).unwrap_err();
    assert_eq!(
        e,
        "error: Sensors: the pin requests `A_b` and `a_b` are the same signal `A_B` in the C header (upper case, anything but a letter or a digit is `_`); rename one"
    );
}

#[test]
fn the_output_is_the_same_on_two_runs() {
    let text = source(REQUESTS);
    assert_eq!(map_of(&text, None), map_of(&text, None));
}

/// The blocks of the guide's section "A pin by capability": the part, the board, the header
/// and the JSON map.
fn guide_blocks() -> (String, String, String, String) {
    let guide =
        fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/LANGUAGE.md"))
            .unwrap();
    let section = guide.split("### A pin by capability").nth(1).unwrap();
    let fenced = |fence: &str| -> String {
        let start = section.find(fence).unwrap() + fence.len();
        let end = section[start..].find("```").unwrap();
        section[start..start + end].to_string()
    };
    (
        fenced("```nsm module=src::zmcu4\n"),
        fenced("```nsm\n"),
        format!(
            "// Generated by netsmith{}",
            fenced("```text\n// Generated by netsmith")
        ),
        format!("{{\n  \"board\"{}", fenced("```text\n{\n  \"board\"")),
    )
}

#[test]
fn the_files_in_the_guide_are_what_a_run_writes() {
    let (part, board, header, json) = guide_blocks();
    let text = board.replace("import src::zmcu4::Zmcu4\n", &format!("{part}\n"));
    let map = map_of(&text, None).unwrap().unwrap();
    assert_eq!(map.header, header);
    assert_eq!(map.json, json);
}
