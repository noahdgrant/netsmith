//! Surface-mount power inductors that a maker draws for one body, and whose pads are the
//! maker's recommended land pattern.
//!
//! The pads of a shielded power inductor are not a function of lead dimensions that IPC-7351
//! describes: each maker's series has its own body, terminals and land pattern, and a part of
//! another maker with the same outline may not share them. Each row here records the pads and
//! the courtyard of the footprint KiCad's library has under the same name (ADR 0043: numbers,
//! which are facts about those footprints), the datasheet that footprint cites, and the page of
//! that datasheet where the land pattern was read. The footprint is named for the maker's
//! series, not for the outline, so a part of another maker does not borrow it by its size.

use super::draw::{Draw, Drawing, Kind, PadSpec, Shape};
use super::outline::SILK_TO_COPPER;
use crate::body3d::Package;
use crate::footprint::{Footprint, Mount};
use crate::geometry::Pt;

const LIBRARY: &str = "Inductor_SMD";

/// One series.
struct Inductor {
    name: &'static str,
    /// The datasheet that the pads were taken from.
    source: &'static str,
    /// Body length (across the pads) and width, in mm.
    body: (f64, f64),
    /// The length of a terminal over each end of the body, in mm (the 3D view only).
    terminal: f64,
    /// The pads as (number, x, y, width, height).
    pads: &'static [(&'static str, f64, f64, f64, f64)],
    /// The courtyard as (min x, min y, max x, max y).
    courtyard: (f64, f64, f64, f64),
}

const PACKAGES: &[Inductor] = &[
    // TDK, Inductors for power circuits, SLF series, SLF7045 type (20190820), page 4/5,
    // Recommended land pattern: two pads 1.5 mm long, 4.8 mm apart, 2.2 mm wide. Terminals
    // 0.9 mm long on a 7.0 x 7.0 mm body (Shape & Dimensions, the same page).
    Inductor {
        name: "L_TDK_SLF7045",
        source: "https://product.tdk.com/info/en/document/catalog/smd/inductor_commercial_power_slf7045_en.pdf",
        body: (7.0, 7.0),
        terminal: 0.9,
        pads: &[("1", -3.15, 0.0, 1.5, 2.2), ("2", 3.15, 0.0, 1.5, 2.2)],
        courtyard: (-4.16, -3.75, 4.16, 3.75),
    },
];

/// Every `Library:Name` this module generates.
pub(super) fn names() -> Vec<String> {
    PACKAGES
        .iter()
        .map(|c| format!("{LIBRARY}:{}", c.name))
        .collect()
}

/// The footprint named `library:name`, if it is a package of this module.
pub(super) fn generate(library: &str, name: &str) -> Option<Footprint> {
    if library != LIBRARY {
        return None;
    }
    PACKAGES.iter().find(|c| c.name == name).map(inductor)
}

fn inductor(c: &Inductor) -> Footprint {
    let mut drawing = Drawing::new(LIBRARY, c.name, Mount::Smd);
    drawing.describe(
        &format!(
            "SMD power inductor, {} x {} mm body, pads as recorded from {}, generated by netsmith",
            c.body.0, c.body.1, c.source
        ),
        "inductor SMD power",
    );
    // The innermost edge of the pads along x.
    let mut inner_x = f64::MAX;
    for &(number, x, y, w, h) in c.pads {
        drawing.pad(&PadSpec::new(
            number,
            Kind::Smd,
            Shape::RoundRect,
            Pt::new(x, y),
            (w, h),
        ));
        inner_x = inner_x.min(x.abs() - w / 2.0);
    }
    let (min_x, min_y, max_x, max_y) = c.courtyard;
    drawing.courtyard(Pt::new(min_x, min_y), Pt::new(max_x, max_y));

    let (hx, hy) = (c.body.0 / 2.0, c.body.1 / 2.0);
    drawing.polygon(
        Draw::Fab,
        &[
            Pt::new(-hx, -hy),
            Pt::new(hx, -hy),
            Pt::new(hx, hy),
            Pt::new(-hx, hy),
        ],
        false,
    );
    drawing.fab_reference((c.body.1 * 0.25).clamp(0.3, 1.0));

    // Silkscreen along the body between the pads, where there is room for it. An inductor has
    // no pin 1: nothing marks a pad.
    let reach = inner_x - SILK_TO_COPPER;
    let silk_y = hy + 0.11;
    if reach > 0.1 {
        for y in [-silk_y, silk_y] {
            drawing.line(Draw::Silk, Pt::new(-reach, y), Pt::new(reach, y));
        }
    }
    let top = -min_y.abs().max(max_y);
    super::shaped(
        drawing.finish(top - 0.7, -top + 0.7),
        Package::Chip {
            body: c.body,
            terminal: c.terminal,
            polarised: false,
        },
    )
}
