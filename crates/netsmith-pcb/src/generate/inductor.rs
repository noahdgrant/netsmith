//! Surface-mount power inductors that a maker draws for one body, and whose pads are the
//! maker's recommended land pattern.
//!
//! The pads of a shielded power inductor are not a function of lead dimensions that IPC-7351
//! describes: each maker's series has its own body, terminals and land pattern, and a part of
//! another maker with the same outline may not share them. Each row here records the pads and
//! the courtyard of the footprint KiCad's library has under the same name (ADR 0043: numbers,
//! which are facts about those footprints), the datasheet that footprint cites, and the page of
//! that datasheet where the land pattern was read. The footprint is named for the maker's
//! series, not for the outline, so a part of another maker does not borrow it by its size.

use super::draw::{Draw, Drawing, Kind, PadSpec, Shape};
use super::outline::SILK_TO_COPPER;
use crate::body3d::Package;
use crate::footprint::{Footprint, Mount};
use crate::geometry::Pt;

const LIBRARY: &str = "Inductor_SMD";

/// The datasheet of the Changjiang FNR series (the one that LCSC links for each of its rows).
const FNR_SHEET: &str =
    "https://datasheet.lcsc.com/datasheet/pdf/a0b12ba9dfe6b9e66b6bb852b7c71c03.pdf";

/// One series.
struct Inductor {
    name: &'static str,
    /// The datasheet that the pads were taken from.
    source: &'static str,
    /// Body length (across the pads) and width, in mm.
    body: (f64, f64),
    /// The length of a terminal over each end of the body, in mm (the 3D view only).
    terminal: f64,
    /// The pads as (number, x, y, width, height).
    pads: &'static [(&'static str, f64, f64, f64, f64)],
    /// The courtyard as (min x, min y, max x, max y).
    courtyard: (f64, f64, f64, f64),
}

