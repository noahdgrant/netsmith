//! The JST PH wire-to-board header, two pins, 2.0 mm pitch, through hole, entering from the side
//! (`Connector_JST:JST_PH_S2B-PH-K_1x02_P2.00mm_Horizontal`): the lead a pouch cell is sold with,
//! a package of `std::sources::Cell` (issue 1366).
//!
//! The pads are 1.2 mm by 1.75 mm round a 0.75 mm hole, pad 1 with square (rounded) corners at the
//! origin and pad 2 the pitch to its right, oval: the land of KiCad 9's footprint of this name
//! (`tests/generated_vs_kicad.rs` holds it to it). The body is the header's housing, 5.9 mm wide
//! (the pitch and 3.9 mm) and 7.6 mm deep, from 1.35 mm behind the leads to 6.25 mm in front of
//! them, where the wire enters; the courtyard is the body and 0.5 mm all round.

use super::draw::{Draw, Drawing, Kind, PadSpec, Shape};
use crate::footprint::{Footprint, Mount};
use crate::geometry::Pt;

const LIBRARY: &str = "Connector_JST";
const NAME: &str = "JST_PH_S2B-PH-K_1x02_P2.00mm_Horizontal";
const PITCH: f64 = 2.0;
const PAD: (f64, f64) = (1.2, 1.75);
const DRILL: f64 = 0.75;
/// The housing round the leads, x from pad 1's lead and y towards the wire.
const BODY: (Pt, Pt) = (Pt { x: -1.95, y: -1.35 }, Pt { x: 3.95, y: 6.25 });

/// Every `Library:Name` this module generates.
pub(super) fn names() -> Vec<String> {
    vec![format!("{LIBRARY}:{NAME}")]
}

/// The footprint named `library:name`, if it is this module's.
pub(super) fn generate(library: &str, name: &str) -> Option<Footprint> {
    (library == LIBRARY && name == NAME).then(header)
}

fn header() -> Footprint {
    let mut d = Drawing::new(LIBRARY, NAME, Mount::ThroughHole);
    d.describe(
        "JST PH series connector, S2B-PH-K, 2 pins, 2.0 mm pitch, side entry, generated by netsmith",
        "connector JST PH horizontal",
    );
    for (number, shape, x) in [(1, Shape::RoundRect, 0.0), (2, Shape::Oval, PITCH)] {
        d.pad(&PadSpec::new(
            number,
            Kind::Through(DRILL),
            shape,
            Pt::new(x, 0.0),
            PAD,
        ));
    }
    let (min, max) = BODY;
    d.courtyard(
        Pt::new(min.x - 0.5, min.y - 0.5),
        Pt::new(max.x + 0.5, max.y + 0.5),
    );
    d.rect(Draw::Fab, min, max);
    let out = 0.11;
    d.rect(
        Draw::Silk,
        Pt::new(min.x - out, PAD.1 / 2.0 + 0.3),
        Pt::new(max.x + out, max.y + out),
    );
    // A triangle on the fabrication layer that points at pin 1.
    d.polygon(
        Draw::Fab,
        &[
            Pt::new(0.0, 0.875),
            Pt::new(-0.5, 1.375),
            Pt::new(0.5, 1.375),
        ],
        false,
    );
    d.fab_reference_at(Pt::new(PITCH / 2.0, 2.5), 1.0);
    d.finish(min.y - 1.2, max.y + 1.2)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_header_has_two_pads_at_its_pitch_and_a_courtyard_round_its_body() {
        let fp = generate(LIBRARY, NAME).unwrap();
        assert_eq!(fp.pad_numbers(), ["1", "2"]);
        assert!((fp.pads[1].at.x - PITCH).abs() < 1e-9);
        assert!((fp.pads[0].drill.unwrap().width - DRILL).abs() < 1e-9);
        assert!((fp.courtyard.min.x + 2.45).abs() < 1e-9);
        assert!((fp.courtyard.max.y - 6.75).abs() < 1e-9);
        assert!(generate(LIBRARY, "JST_PH_S3B-PH-K_1x03_P2.00mm_Horizontal").is_none());
    }
}
