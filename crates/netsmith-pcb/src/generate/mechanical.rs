//! What is on a board and not in its circuit, or on it by one pad: the mounting holes, the
//! test points and the fiducial (`MountingHole:MountingHole_3.2mm_M3`,
//! `TestPoint:TestPoint_Pad_D1.5mm`, `Fiducial:Fiducial_1mm_Mask2mm`).
//!
//! Each is a circle round the origin, and its numbers follow from the name:
//!
//! - A mounting hole is a drill of the clearance of a screw (3.2 mm for M3, 2.2 mm for M2).
//!   The plain one is a hole with no copper. The `_Pad` one is plated, with an annulus as
//!   wide as the hole is, so that the pad is twice the drill and a screw head and a washer
//!   rest on copper that is bonded to a net. The screw head needs a ring as wide as the
//!   drill round the hole (drawn on the comment layer, a note to the person), and the
//!   courtyard is 0.25 mm outside it.
//! - A test point is a bare round pad of the diameter in its name, with the mask open over
//!   it and no paste: a probe touches copper. A ring on the silkscreen 0.2 mm outside the
//!   pad marks it, and the courtyard is 0.5 mm outside the pad.
//! - The fiducial is a round copper mark 1 mm across, alone in a mask opening 2 mm across
//!   (a margin of 0.5 mm), with 0.5 mm of bare board round it so that a camera sees the
//!   edge of the copper. It has no paste. The courtyard is 0.25 mm outside the opening.
//!
//! None of the three is fitted by anyone or on a bill of materials, so each says so in its
//! `attr` (the fiducial, as KiCad's, only says it is surface mount).

use super::draw::{Draw, Drawing, Kind, PadSpec, Shape};
use crate::footprint::{Footprint, Mount};
use crate::geometry::Pt;

/// A footprint of this module, with the numbers its name gives.
enum Item {
    Hole {
        /// The drill, as the name spells it, and in mm.
        drill_text: &'static str,
        drill: f64,
        screw: &'static str,
        plated: bool,
    },
    TestPoint {
        diameter_text: &'static str,
        diameter: f64,
    },
    Fiducial,
}

const ITEMS: [Item; 8] = [
    Item::Hole {
        drill_text: "3.2",
        drill: 3.2,
        screw: "M3",
        plated: false,
    },
    Item::Hole {
        drill_text: "3.2",
        drill: 3.2,
        screw: "M3",
        plated: true,
    },
    Item::Hole {
        drill_text: "2.2",
        drill: 2.2,
        screw: "M2",
        plated: false,
    },
    Item::Hole {
        drill_text: "2.2",
        drill: 2.2,
        screw: "M2",
        plated: true,
    },
    Item::TestPoint {
        diameter_text: "1.0",
        diameter: 1.0,
    },
    Item::TestPoint {
        diameter_text: "1.5",
        diameter: 1.5,
    },
    Item::TestPoint {
        diameter_text: "2.0",
        diameter: 2.0,
    },
    Item::Fiducial,
];

/// The mounting of a part that nobody fits and no list names.
const NOT_FITTED: &str = "exclude_from_pos_files exclude_from_bom";

impl Item {
    fn library(&self) -> &'static str {
        match self {
            Item::Hole { .. } => "MountingHole",
            Item::TestPoint { .. } => "TestPoint",
            Item::Fiducial => "Fiducial",
        }
    }

    fn name(&self) -> String {
        match self {
            Item::Hole {
                drill_text,
                screw,
                plated,
                ..
            } => format!(
                "MountingHole_{drill_text}mm_{screw}{}",
                if *plated { "_Pad" } else { "" }
            ),
            Item::TestPoint { diameter_text, .. } => format!("TestPoint_Pad_D{diameter_text}mm"),
            Item::Fiducial => "Fiducial_1mm_Mask2mm".to_string(),
        }
    }
}

/// Every `Library:Name` this module generates.
pub(super) fn names() -> Vec<String> {
    ITEMS
        .iter()
        .map(|i| format!("{}:{}", i.library(), i.name()))
        .collect()
}

/// The footprint named `library:name`, if it is one of this module's.
pub(super) fn generate(library: &str, name: &str) -> Option<Footprint> {
    let item = ITEMS
        .iter()
        .find(|i| i.library() == library && i.name() == name)?;
    Some(match item {
        Item::Hole {
            drill,
            screw,
            plated,
            ..
        } => hole(&item.name(), *drill, screw, *plated),
        Item::TestPoint { diameter, .. } => test_point(&item.name(), *diameter),
        Item::Fiducial => fiducial(&item.name()),
    })
}

fn hole(name: &str, drill: f64, screw: &str, plated: bool) -> Footprint {
    let mut d = Drawing::new("MountingHole", name, Mount::ThroughHole);
    let plating = if plated { "plated" } else { "no copper" };
    d.describe(
        &format!("Mounting hole, {drill} mm drill, {plating}, for an {screw} screw, generated by netsmith"),
        &format!(
            "mounting hole {drill}mm {} {}",
            screw.to_lowercase(),
            if plated { "plated" } else { "no annular" }
        ),
    );
    d.attr(NOT_FITTED);
    d.without_model();
    // The room a screw head and its washer take, as wide as the hole.
    d.circle(Draw::Comments, drill);
    let reach = drill + 0.25;
    d.courtyard_circle(reach);
    d.fab_reference(1.0);
    if plated {
        d.pad(
            &PadSpec::new(
                1,
                Kind::Through(drill),
                Shape::Circle,
                Pt::new(0.0, 0.0),
                (2.0 * drill, 2.0 * drill),
            )
            .keeping_all_layers(),
        );
    } else {
        d.pad(&PadSpec::new(
            "",
            Kind::NonPlated(drill),
            Shape::Circle,
            Pt::new(0.0, 0.0),
            (drill, drill),
        ));
    }
    d.finish(-(reach + 0.75), reach + 0.75)
}

fn test_point(name: &str, diameter: f64) -> Footprint {
    let mut d = Drawing::new("TestPoint", name, Mount::Smd);
    d.describe(
        &format!("Test point, a bare round pad {diameter:.1} mm across, generated by netsmith"),
        "test point pad",
    );
    d.attr(NOT_FITTED);
    d.without_model();
    d.pad(&PadSpec::new(
        1,
        Kind::SmdNoPaste,
        Shape::Circle,
        Pt::new(0.0, 0.0),
        (diameter, diameter),
    ));
    d.circle(Draw::Silk, diameter / 2.0 + 0.2);
    let reach = diameter / 2.0 + 0.5;
    d.courtyard_circle(reach);
    let label = reach + 0.75;
    d.fab_reference_at(Pt::new(0.0, -label), 1.0);
    d.finish(-label, label)
}

fn fiducial(name: &str) -> Footprint {
    const COPPER: f64 = 1.0;
    const MASK_MARGIN: f64 = 0.5;
    let mut d = Drawing::new("Fiducial", name, Mount::Smd);
    d.describe(
        "Round fiducial, 1 mm of bare copper in a mask opening 2 mm across, generated by netsmith",
        "fiducial",
    );
    d.without_model();
    let opening = COPPER / 2.0 + MASK_MARGIN;
    d.courtyard_circle(opening + 0.25);
    d.circle(Draw::Fab, opening);
    d.fab_reference(0.4);
    d.pad(
        &PadSpec::new(
            "",
            Kind::SmdNoPaste,
            Shape::Circle,
            Pt::new(0.0, 0.0),
            (COPPER, COPPER),
        )
        .with_mask_margin(MASK_MARGIN)
        .with_clearance(0.5),
    );
    d.finish(-(opening + 1.0), opening + 1.0)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::footprint::{Layer, PadKind, PadShape};
    use crate::geometry::Rect;

    fn near(a: f64, b: f64) -> bool {
        (a - b).abs() < 1e-9
    }

    fn make(id: &str) -> Footprint {
        let (library, name) = id.split_once(':').unwrap();
        generate(library, name).unwrap_or_else(|| panic!("{id} is not generated"))
    }

    fn circle_radii(fp: &Footprint, layer: Layer) -> Vec<f64> {
        fp.graphics
            .iter()
            .filter(|g| g.layer == layer)
            .filter_map(|g| match g.shape {
                crate::footprint::Shape::Circle { radius, .. } => Some(radius),
                _ => None,
            })
            .collect()
    }

    #[test]
    fn exactly_the_eight_ids_of_the_standard_mapping_are_made() {
        assert_eq!(
            names(),
            [
                "MountingHole:MountingHole_3.2mm_M3",
                "MountingHole:MountingHole_3.2mm_M3_Pad",
                "MountingHole:MountingHole_2.2mm_M2",
                "MountingHole:MountingHole_2.2mm_M2_Pad",
                "TestPoint:TestPoint_Pad_D1.0mm",
                "TestPoint:TestPoint_Pad_D1.5mm",
                "TestPoint:TestPoint_Pad_D2.0mm",
                "Fiducial:Fiducial_1mm_Mask2mm",
            ]
        );
        for id in [
            "MountingHole:MountingHole_3.4mm_M3",
            "MountingHole:MountingHole_3.2mm_M2",
            "TestPoint:TestPoint_Pad_D2.5mm",
            "TestPoint:TestPoint_Pad_D1.5mm_Pad",
            "Fiducial:Fiducial_1mm_Mask2.0mm",
            "Fiducial:TestPoint_Pad_D1.0mm",
        ] {
            let (library, name) = id.split_once(':').unwrap();
            assert!(generate(library, name).is_none(), "{id}");
        }
    }

    #[test]
    fn a_plain_hole_is_one_unplated_drill_the_size_of_its_name_with_no_copper_and_no_number() {
        for (id, drill) in [
            ("MountingHole:MountingHole_3.2mm_M3", 3.2),
            ("MountingHole:MountingHole_2.2mm_M2", 2.2),
        ] {
            let fp = make(id);
            assert_eq!(fp.mount, Mount::ThroughHole, "{id}");
            assert_eq!(fp.pads.len(), 1, "{id}");
            let pad = &fp.pads[0];
            assert_eq!(pad.number, "", "{id}");
            assert_eq!(
                (pad.kind, pad.shape),
                (PadKind::NpThruHole, PadShape::Circle)
            );
            assert!(near(pad.width, drill) && near(pad.height, drill), "{id}");
            let hole = pad.drill.unwrap();
            assert!(near(hole.width, drill) && near(hole.height, drill), "{id}");
            assert_eq!(pad.layers, ["*.Cu", "*.Mask"], "{id}");
            assert_eq!(pad.copper_layers(), (false, false), "{id}");
            // The courtyard is a circle 0.25 mm outside the room of the screw head.
            let reach = drill + 0.25;
            assert_eq!(
                fp.courtyard,
                Rect::new(Pt::new(-reach, -reach), Pt::new(reach, reach)),
                "{id}"
            );
            assert_eq!(circle_radii(&fp, Layer::Courtyard), [reach], "{id}");
            assert!(near(fp.reference_at.y, -(reach + 0.75)), "{id}");
            // Nothing is drawn on the fabrication layer, so the body is the courtyard.
            assert!(fp.body_is_courtyard, "{id}");
        }
    }

    #[test]
    fn a_plated_hole_has_a_pad_twice_its_drill_numbered_1_and_copper_on_both_faces() {
        for (id, drill) in [
            ("MountingHole:MountingHole_3.2mm_M3_Pad", 3.2),
            ("MountingHole:MountingHole_2.2mm_M2_Pad", 2.2),
        ] {
            let fp = make(id);
            assert_eq!(fp.mount, Mount::ThroughHole, "{id}");
            assert_eq!(fp.pad_numbers(), ["1"], "{id}");
            let pad = &fp.pads[0];
            assert_eq!((pad.kind, pad.shape), (PadKind::ThruHole, PadShape::Circle));
            assert!(near(pad.width, 2.0 * drill) && near(pad.height, 2.0 * drill));
            assert!(near(pad.drill.unwrap().width, drill), "{id}");
            assert_eq!(pad.copper_layers(), (true, true), "{id}");
            assert_eq!(pad.layers, ["*.Cu", "*.Mask"], "{id}");
            // The plating stays on the inner layers that nothing connects to.
            assert!(
                fp.source
                    .to_kicad_string()
                    .contains("(remove_unused_layers no)")
            );
            assert_eq!(circle_radii(&fp, Layer::Courtyard), [drill + 0.25], "{id}");
        }
    }

    #[test]
    fn a_hole_is_on_no_bill_of_materials_and_names_no_3d_model() {
        for id in [
            "MountingHole:MountingHole_3.2mm_M3",
            "MountingHole:MountingHole_2.2mm_M2_Pad",
            "TestPoint:TestPoint_Pad_D1.0mm",
        ] {
            let text = make(id).source.to_kicad_string();
            assert!(
                text.contains("(attr exclude_from_pos_files exclude_from_bom)"),
                "{id}"
            );
            assert!(!text.contains("(model"), "{id}");
        }
    }

    #[test]
    fn every_footprint_says_what_kicads_own_says_of_the_bill_and_the_position_file() {
        // KiCad 9's own: a hole and a test point are `exclude_from_pos_files exclude_from_bom`
        // and no more (a test point is not `smd` too), and the fiducial is only `smd`, so that
        // the pick-and-place machine finds it in a position file.
        // `generated_vs_kicad.rs` compares the words with the installed library's.
        for id in names() {
            let text = make(&id).source.to_kicad_string();
            let attr = if id.starts_with("Fiducial:") {
                "(attr smd)"
            } else {
                "(attr exclude_from_pos_files exclude_from_bom)"
            };
            assert_eq!(text.matches("(attr ").count(), 1, "{id}");
            assert!(text.contains(attr), "{id}: {text}");
        }
    }

    #[test]
    fn a_test_point_is_one_bare_round_pad_with_mask_open_and_no_paste() {
        for (id, d) in [
            ("TestPoint:TestPoint_Pad_D1.0mm", 1.0),
            ("TestPoint:TestPoint_Pad_D1.5mm", 1.5),
            ("TestPoint:TestPoint_Pad_D2.0mm", 2.0),
        ] {
            let fp = make(id);
            assert_eq!(fp.mount, Mount::Smd, "{id}");
            assert_eq!(fp.pad_numbers(), ["1"], "{id}");
            let pad = &fp.pads[0];
            assert_eq!((pad.kind, pad.shape), (PadKind::Smd, PadShape::Circle));
            assert!(near(pad.width, d) && near(pad.height, d), "{id}");
            assert!(pad.drill.is_none(), "{id}");
            // Copper and mask, and no paste: nothing is soldered to a test point.
            assert_eq!(pad.layers, ["F.Cu", "F.Mask"], "{id}");
            let reach = d / 2.0 + 0.5;
            assert_eq!(circle_radii(&fp, Layer::Courtyard), [reach], "{id}");
            assert_eq!(
                fp.courtyard,
                Rect::new(Pt::new(-reach, -reach), Pt::new(reach, reach)),
                "{id}"
            );
            // A ring 0.2 mm outside the pad on the silkscreen.
            assert_eq!(circle_radii(&fp, Layer::Silk), [d / 2.0 + 0.2], "{id}");
        }
    }

    #[test]
    fn the_fiducial_is_a_copper_dot_1_mm_across_in_a_mask_opening_2_mm_across() {
        let fp = make("Fiducial:Fiducial_1mm_Mask2mm");
        assert_eq!(fp.mount, Mount::Smd);
        assert_eq!(fp.pads.len(), 1);
        let pad = &fp.pads[0];
        assert_eq!(pad.number, "");
        assert_eq!((pad.kind, pad.shape), (PadKind::Smd, PadShape::Circle));
        assert!(near(pad.width, 1.0) && near(pad.height, 1.0));
        assert_eq!(pad.layers, ["F.Cu", "F.Mask"]);
        assert_eq!(pad.clearance, Some(0.5));
        // The mask opens 0.5 mm beyond the copper, which is 2 mm across, and the file says so.
        let text = fp.source.to_kicad_string();
        assert!(text.contains("(solder_mask_margin 0.5)"), "{text}");
        assert_eq!(circle_radii(&fp, Layer::Fab), [1.0]);
        assert_eq!(circle_radii(&fp, Layer::Courtyard), [1.25]);
        assert_eq!(
            fp.courtyard,
            Rect::new(Pt::new(-1.25, -1.25), Pt::new(1.25, 1.25))
        );
        assert!(text.contains("(attr smd)"), "{text}");
    }
}
