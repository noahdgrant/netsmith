//! The pin map for the firmware author: `fab` writes `<board>.pins.h` and `<board>.pins.json`
//! into the board's `fab/` folder, from the pins the board was routed with, when it has pin
//! requests (ADR 0101), naming each signal by its request. `build` writes none: its pins are
//! provisional (owner decision of 2026-11-11).

use std::fs;
use std::path::Path;

use crate::pin_swaps::{netsmith, project};
use netsmith::pin_export::{PinMap, render};
use netsmith_check::Loader;
use netsmith_kicad::testlib::TempDir;

const PART: &str = r#"
/// Zmcu4, an invented microcontroller: the datasheet names of its pins differ in how they end.
part Zmcu4 {
    peripheral UARTE0 on GPIO { UARTE0_TX:output UARTE0_RX:input }
    pins {
        .p00 bidirectional "GPIO7" "1" fn GPIO
        .p01 bidirectional "P0.13" "2" fn GPIO
        .p02 bidirectional "P0.02" "3" fn GPIO ANALOG
        .p03 bidirectional "P0.03" "4" fn GPIO ANALOG
    }
}
"#;

fn source(requests: &str) -> String {
    format!(
        "import std::parts::passive::Resistor\n{PART}\nboard Sensors {{\n    .u: Zmcu4\n    .load: Resistor\n{requests}\n}}\n"
    )
}

const REQUESTS: &str = "    .status: .u.GPIO\n    .sense: .u.ANALOG\n    .status ~ .load.a\n";

/// The pin map of the first board of `text`, with `pin_file` as the pin file beside it.
fn map_of(text: &str, pin_file: Option<&str>) -> Result<Option<PinMap>, String> {
    let dir = TempDir::new("pin-export");
    let path = dir.path().join("main.nsm");
    let mut loader = Loader::std();
    if let Some(file) = pin_file {
        fs::write(path.with_extension("pins.toml"), file).unwrap();
        netsmith::pins::attach(&mut loader, "main.nsm", &path, &Default::default()).unwrap();
    }
    let outcome = netsmith::outcome_with(
        "main.nsm",
        text,
        &loader,
        &netsmith_solve::Catalogs::jlcpcb(),
        None,
    )
    .map_err(|p| netsmith::render_problems(&p))?;
    let b = &outcome.boards[0];
    let spaces = outcome
        .pins
        .spaces
        .get(&b.board)
        .map_or(&[][..], Vec::as_slice);
    render(&b.design, spaces, "main.nsm")
}

#[test]
fn the_header_names_each_signal_by_its_request() {
    let map = map_of(&source(REQUESTS), None).unwrap().unwrap();
    assert_eq!(
        map.header,
        r#"// Generated by netsmith from main.nsm. Do not edit: run `netsmith fab` again.
// The pins of the requests of board Sensors.
#ifndef SENSORS_PINS_H
#define SENSORS_PINS_H

// sense: pin P0.02, pad 3 of u, function ANALOG
#define SENSORS_PIN_SENSE_NAME "P0.02"
#define SENSORS_PIN_SENSE_FUNCTION "ANALOG"

// status: pin GPIO7, pad 1 of u, function GPIO
#define SENSORS_PIN_STATUS_NAME "GPIO7"
#define SENSORS_PIN_STATUS_FUNCTION "GPIO"
#define SENSORS_PIN_STATUS_NUMBER 7

#endif // SENSORS_PINS_H
"#
    );
}

#[test]
fn the_json_map_has_sorted_keys_and_the_lock_of_the_pin_file() {
    let file = "version = 1\n\n[Sensors.pins.sense]\npin = \"p02\"\nfunction = \"ANALOG\"\nlock = true\nsource = \"hand\"\n";
    let map = map_of(&source(REQUESTS), Some(file)).unwrap().unwrap();
    assert_eq!(
        map.json,
        r#"{
  "board": "Sensors",
  "signals": {
    "sense": {
      "function": "ANALOG",
      "locked": true,
      "pad": "3",
      "part": "u",
      "pin": "P0.02"
    },
    "status": {
      "function": "GPIO",
      "locked": false,
      "pad": "1",
      "part": "u",
      "pin": "GPIO7"
    }
  },
  "source": "main.nsm"
}
"#
    );
    assert!(
        map.header
            .contains("// sense: pin P0.02, pad 3 of u, function ANALOG, locked\n")
    );
}

#[test]
fn a_pin_name_without_one_trailing_number_has_no_numeric_macro() {
    // `.sense` gets `P0.02`: two numbers, so none is guessed.
    let map = map_of(&source(REQUESTS), None).unwrap().unwrap();
    assert!(!map.header.contains("SENSORS_PIN_SENSE_NUMBER"));
    assert!(map.header.contains("SENSORS_PIN_STATUS_NUMBER 7"));
}

#[test]
fn a_board_with_no_request_has_no_pin_map() {
    let text = "import std::parts::passive::Resistor\nboard Plain {\n    .a: Resistor\n    .b: Resistor\n    .a.a ~ .b.a\n}\n";
    assert_eq!(map_of(text, None).unwrap(), None);
}

#[test]
fn two_requests_that_are_one_signal_in_c_are_an_error_naming_both() {
    let text = source("    .a_b: .u.GPIO\n    .A_b: .u.GPIO\n    .a_b ~ .load.a\n");
    let e = map_of(&text, None).unwrap_err();
    assert_eq!(
        e,
        "error: Sensors: the pin requests `A_b` and `a_b` are the same signal `A_B` in the C header (upper case, anything but a letter or a digit is `_`); rename one"
    );
}

#[test]
fn the_output_is_the_same_on_two_runs() {
    let text = source(REQUESTS);
    assert_eq!(map_of(&text, None), map_of(&text, None));
}

/// What the binary writes: `build` in a project folder.
fn build(dir: &Path) -> std::process::Output {
    std::process::Command::new(env!("CARGO_BIN_EXE_netsmith"))
        .current_dir(dir)
        .args(["build", "main.nsm", "--out", "out"])
        .output()
        .unwrap()
}

/// The files of a project in `dir` that builds `Zmcu4`: its footprint is the generator's, so no
/// KiCad is read.
fn write_project(dir: &Path) {
    fs::write(
        dir.join("netsmith.toml"),
        "[project]\nname = \"export\"\ntop_level = [\"main.nsm\"]\nkicad = 9\n",
    )
    .unwrap();
    fs::write(
        dir.join("kicad.toml"),
        "[[part]]\nkind = \"Zmcu4\"\npackage = \"HDR-4\"\ndefault = true\nfootprint = \"gen:PinHeader(rows=1, pins=4, pitch=2.54mm)\"\n",
    )
    .unwrap();
}

#[test]
fn build_writes_no_pin_map_and_touches_none_that_fab_wrote() {
    let dir = TempDir::new("pin-export-build");
    write_project(dir.path());
    fs::write(dir.path().join("main.nsm"), source(REQUESTS)).unwrap();
    let board = dir.path().join("out/Sensors");
    // What an earlier `fab` left in the folder `build` writes to (`--out` can name one folder
    // for both): `build` neither adds to it nor removes it, whether the board has requests or
    // not.
    fs::create_dir_all(&board).unwrap();
    let kept = [
        (board.join("Sensors.pins.h"), "header of fab"),
        (board.join("Sensors.pins.json"), "json of fab"),
    ];
    for (file, text) in &kept {
        fs::write(file, text).unwrap();
    }
    for requests in [REQUESTS, ""] {
        fs::write(dir.path().join("main.nsm"), source(requests)).unwrap();
        let out = build(dir.path());
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
        assert!(board.join("Sensors.kicad_sch").exists());
        for (file, text) in &kept {
            assert_eq!(&fs::read_to_string(file).unwrap(), text, "{requests:?}");
        }
    }
    // With nothing there, it writes none.
    for (file, _) in &kept {
        fs::remove_file(file).unwrap();
    }
    fs::write(dir.path().join("main.nsm"), source(REQUESTS)).unwrap();
    let out = build(dir.path());
    assert!(out.status.success());
    assert!(board.join("Sensors.kicad_sch").exists());
    assert!(!board.join("Sensors.pins.h").exists());
    assert!(!board.join("Sensors.pins.json").exists());
}

/// `fab` on the project of `dir` (the board of `pin_swaps`: ten requests on a microcontroller
/// joined to a connector, which routes only with some pin maps), with `args` after the flag that
/// lets the unassembled parts through.
fn fab(cwd: &Path, args: &[&str]) -> std::process::Output {
    let mut all = vec!["fab", "--allow-drc-violations"];
    all.extend_from_slice(args);
    netsmith(cwd, &all)
}

fn succeeded(out: &std::process::Output) {
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
}

/// The pin map files `fab` wrote for the board `Swaps` below `fab_dir`.
fn files_of(fab_dir: &Path) -> (String, String) {
    let board = fab_dir.join("Swaps");
    (
        fs::read_to_string(board.join("Swaps.pins.h")).unwrap(),
        fs::read_to_string(board.join("Swaps.pins.json")).unwrap(),
    )
}

/// The header the board `Swaps` has when request `gKK` is on pin `pNN` for `NN = pins[K - 1]`:
/// the pin is `P0.NN` and its pad `NN + 1`.
fn swaps_header(pins: &[usize], locked: bool, source: &str) -> String {
    let mut out = format!(
        "// Generated by netsmith from {source}. Do not edit: run `netsmith fab` again.\n// The pins of the requests of board Swaps.\n#ifndef SWAPS_PINS_H\n#define SWAPS_PINS_H\n"
    );
    for (k, p) in pins.iter().enumerate() {
        let k = k + 1;
        let locked = if locked { ", locked" } else { "" };
        out.push_str(&format!(
            "\n// g{k:02}: pin P0.{p:02}, pad {} of u, function GPIO{locked}\n#define SWAPS_PIN_G{k:02}_NAME \"P0.{p:02}\"\n#define SWAPS_PIN_G{k:02}_FUNCTION \"GPIO\"\n",
            p + 1
        ));
    }
    out.push_str("\n#endif // SWAPS_PINS_H\n");
    out
}

/// The JSON map of the same board.
fn swaps_json(pins: &[usize], locked: bool, source: &str) -> String {
    let signals: Vec<String> = pins
        .iter()
        .enumerate()
        .map(|(k, p)| {
            format!(
                "    \"g{:02}\": {{\n      \"function\": \"GPIO\",\n      \"locked\": {locked},\n      \"pad\": \"{}\",\n      \"part\": \"u\",\n      \"pin\": \"P0.{p:02}\"\n    }}",
                k + 1,
                p + 1
            )
        })
        .collect();
    format!(
        "{{\n  \"board\": \"Swaps\",\n  \"signals\": {{\n{}\n  }},\n  \"source\": \"{source}\"\n}}\n",
        signals.join(",\n")
    )
}

/// The pin of request `gKK` in a pin file's text.
fn pins_in(file: &str) -> Vec<usize> {
    (1..=10)
        .map(|k| {
            let table = format!("[Swaps.pins.g{k:02}]\npin = \"p");
            let at = file.find(&table).unwrap_or_else(|| panic!("{file}"));
            file[at + table.len()..][..2].parse().unwrap()
        })
        .collect()
}

/// The pin file that locks every request on the pins that route: mirrored.
fn routing_pins() -> Vec<usize> {
    (0..10).rev().collect()
}

/// A project of the swaps board whose pin file is `routing_pins`, locked.
fn routing_project(root: &Path) {
    project(root);
    fs::write(
        root.join("src/main.pins.toml"),
        crate::pin_swaps::locked_pins(&routing_pins()),
    )
    .unwrap();
}

#[test]
fn fab_writes_the_header_and_the_json_into_the_boards_fab_folder() {
    let root = TempDir::new("pin-export-fab");
    routing_project(root.path());
    succeeded(&fab(root.path(), &[]));
    let (header, json) = files_of(&root.join("fab"));
    assert_eq!(header, swaps_header(&routing_pins(), true, "src/main.nsm"));
    assert_eq!(json, swaps_json(&routing_pins(), true, "src/main.nsm"));
    // Beside the other files of the package, and `build` put none in its own folder.
    assert!(root.join("fab/Swaps/Swaps.kicad_pcb").exists());
    assert!(root.join("fab/Swaps/bom.csv").exists());
}

#[test]
fn the_files_are_the_pins_the_board_was_routed_with_when_the_optimizer_moved_them() {
    let root = TempDir::new("pin-export-moved");
    project(root.path());
    // `build` writes no pin map: its pins are provisional.
    succeeded(&netsmith(root.path(), &["build"]));
    assert!(root.join("out/Swaps/Swaps.kicad_sch").exists());
    assert!(!root.join("out/Swaps/Swaps.pins.h").exists());
    assert!(!root.join("out/Swaps/Swaps.pins.json").exists());

    // The first assignment (`p00` to `p09` in order) does not route: `fab` moves pins, and the
    // files say where they ended.
    succeeded(&fab(root.path(), &[]));
    let pin_file = fs::read_to_string(root.join("src/main.pins.toml")).unwrap();
    let pins = pins_in(&pin_file);
    assert_ne!(
        pins,
        (0..10).collect::<Vec<_>>(),
        "the optimizer moved no pin: {pin_file}"
    );
    let (header, json) = files_of(&root.join("fab"));
    assert_eq!(header, swaps_header(&pins, false, "src/main.nsm"));
    assert_eq!(json, swaps_json(&pins, false, "src/main.nsm"));

    // `build` into the folder `fab` wrote leaves its pin map as it is.
    succeeded(&netsmith(root.path(), &["build", "--out", "fab"]));
    assert!(root.join("fab/Swaps/Swaps.kicad_sch").exists());
    assert_eq!(files_of(&root.join("fab")), (header, json));
}

#[test]
fn the_files_are_the_same_on_every_run_from_every_directory_and_with_locked() {
    let root = TempDir::new("pin-export-same");
    routing_project(root.path());
    let src = root.join("src");
    let runs = [
        (root.path().to_path_buf(), vec!["src/main.nsm"]),
        (src.clone(), vec!["main.nsm"]),
        (src.clone(), vec!["../src/main.nsm"]),
        // `--locked` reads the pin file and the pick lock the first run wrote, and exports too.
        (root.path().to_path_buf(), vec!["--locked"]),
    ];
    let mut made = Vec::new();
    for (i, (cwd, args)) in runs.iter().enumerate() {
        let out = root.join(format!("out{i}"));
        let out_arg = out.display().to_string();
        let mut all = args.clone();
        all.extend(["--out", &out_arg]);
        succeeded(&fab(cwd, &all));
        made.push(files_of(&out));
    }
    assert!(made[0].0.contains("from src/main.nsm."), "{}", made[0].0);
    assert!(made[0].1.contains("\"source\": \"src/main.nsm\""));
    for other in &made[1..] {
        assert_eq!(&made[0], other);
    }
}

#[test]
fn a_board_with_no_request_gets_none_and_fab_removes_the_two_it_wrote_before() {
    let root = TempDir::new("pin-export-gone");
    routing_project(root.path());
    succeeded(&fab(root.path(), &[]));
    let board = root.join("fab/Swaps");
    assert!(board.join("Swaps.pins.h").exists());
    assert!(board.join("Swaps.pins.json").exists());

    // The same board with its ten requests written as pins: it routes the same way.
    let main = root.join("src/main.nsm");
    let mut text = fs::read_to_string(&main).unwrap();
    for k in 1..=10 {
        text = text.replace(&format!("    .g{k:02}: .u.GPIO\n"), "");
        text = text.replace(
            &format!(".g{k:02} ~ .j.p{}", 11 - k),
            &format!(".u.p{:02} ~ .j.p{}", 10 - k, 11 - k),
        );
    }
    // The pins the requests had are chosen by hand now.
    let functions: String = (0..10)
        .map(|p| format!("        .p{p:02}.function &= \"GPIO\"\n"))
        .collect();
    text = text.replace(
        "    .u: Zmcu { .assembly &= AssemblyMode::Hand }\n",
        &format!("    .u: Zmcu {{\n        .assembly &= AssemblyMode::Hand\n{functions}    }}\n"),
    );
    fs::write(&main, text).unwrap();
    fs::remove_file(root.join("src/main.pins.toml")).unwrap();
    succeeded(&fab(root.path(), &[]));
    assert!(board.join("Swaps.kicad_pcb").exists());
    assert!(board.join("bom.csv").exists());
    assert!(!board.join("Swaps.pins.h").exists());
    assert!(!board.join("Swaps.pins.json").exists());
}

#[test]
fn two_requests_that_are_one_signal_stop_fab_before_any_board_is_placed() {
    let root = TempDir::new("pin-export-collision");
    project(root.path());
    fs::remove_file(root.join("src/main.pins.toml")).unwrap();
    let main = root.join("src/main.nsm");
    let text = fs::read_to_string(&main)
        .unwrap()
        .replace("    .g01: .u.GPIO\n", "    .a_b: .u.GPIO\n")
        .replace("    .g02: .u.GPIO\n", "    .A_b: .u.GPIO\n")
        .replace(".g01 ~", ".a_b ~")
        .replace(".g02 ~", ".A_b ~");
    fs::write(&main, text).unwrap();
    let out = fab(root.path(), &[]);
    assert!(!out.status.success());
    let err = String::from_utf8_lossy(&out.stderr);
    assert!(
        err.contains("the pin requests `A_b` and `a_b` are the same signal `A_B`"),
        "{err}"
    );
    // The check is the first of `fab`'s stages: no board was placed, and nothing was written.
    assert!(!err.contains("placing"), "{err}");
    assert!(!root.join("fab").exists());
}

/// The blocks of the guide's section "A pin by capability": the part, the board, the header
/// and the JSON map.
fn guide_blocks() -> (String, String, String, String) {
    let guide =
        fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/LANGUAGE.md"))
            .unwrap();
    let section = guide.split("### A pin by capability").nth(1).unwrap();
    let fenced = |fence: &str| -> String {
        let start = section.find(fence).unwrap() + fence.len();
        let end = section[start..].find("```").unwrap();
        section[start..start + end].to_string()
    };
    (
        fenced("```nsm module=src::zmcu4\n"),
        fenced("```nsm\n"),
        format!(
            "// Generated by netsmith{}",
            fenced("```text\n// Generated by netsmith")
        ),
        format!("{{\n  \"board\"{}", fenced("```text\n{\n  \"board\"")),
    )
}

#[test]
fn the_files_in_the_guide_are_what_a_run_writes() {
    let (part, board, header, json) = guide_blocks();
    let text = board.replace("import src::zmcu4::Zmcu4\n", &format!("{part}\n"));
    let map = map_of(&text, None).unwrap().unwrap();
    assert_eq!(map.header, header);
    assert_eq!(map.json, json);
}
